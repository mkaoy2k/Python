"""
這個程式使用巢狀迴圈印出一個星號圖形（米字型）。

主要功能：
- 設定圖形大小為 n x n（預設為 7）
- 使用雙重迴圈遍歷每一個位置
- 當位置位於對角線、反對角線、中間橫線或中間直線時印出星號
程式碼利用兩個巢狀迴圈（i 代表列索引，j 代表行索引，範圍皆為 0 到 6）遍歷一個 7×7 的矩陣，並透過四個條件的 or 組合來決定何時印出星號 *：
	1. i == j：主對角線（左上到右下）。
	2. i + j == n - 1（即 i + j == 6）：副對角線（右上到左下）。
	3. i == n // 2（即 i == 3）：水平中央線（第 4 列）。
	4. j == n // 2（即 j == 3）：垂直中央線（第 4 行）。
	當 i 和 j 的位置符合上述任一條件時，程式會印出 *；其餘位置則印出空格 " "。

- 最終形成一個米字型的星號圖形
"""

n = 7

for i in range(n):
    for j in range(n):
        if i == j or i + j == n - 1 or i == n // 2 or j == n // 2:
            print("*", end=" ")
        else:
            print(" ", end=" ")
    print()